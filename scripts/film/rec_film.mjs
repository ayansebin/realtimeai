import fs from 'fs';
import path from 'path';
const { chromium } = await import(process.env.PLAYWRIGHT || 'playwright');
const HERE = path.dirname(new URL(import.meta.url).pathname);
const SITE = process.env.SITE || 'http://127.0.0.1:8800/';
const FONTS = process.env.FONTS_DIR || 'node_modules/@fontsource';
const rd = f => fs.readFileSync(path.join(HERE, f), 'utf8');
const OUT=process.argv[2]||'film',SECS=+(process.argv[3]||170);
fs.rmSync(OUT,{recursive:true,force:true});fs.mkdirSync(OUT,{recursive:true});
const b=await chromium.launch({args:['--force-device-scale-factor=1.5','--window-size=1280,720','--hide-scrollbars','--autoplay-policy=no-user-gesture-required']});
const ctx=await b.newContext({viewport:null});
await ctx.route(/fonts\.googleapis\.com/,r=>r.fulfill({contentType:'text/css',body:rd('fonts.css')}));
await ctx.route(/fonts\.gstatic\.com/,r=>r.abort());
await ctx.route(/\/__f\//,r=>{const f=r.request().url().split('/').pop();const d=f.includes('mono')?'ibm-plex-mono':'ibm-plex-sans';r.fulfill({contentType:'font/woff2',body:fs.readFileSync(FONTS+'/'+d+'/files/'+f)});});
await ctx.addInitScript(()=>{window.__filmCapture=true;window.__plays=[];const p=HTMLMediaElement.prototype.play;HTMLMediaElement.prototype.play=function(){if(!this.muted)window.__plays.push({src:this.src,t:Date.now()});return p.apply(this,arguments);};
  try{localStorage.setItem('rti-demo-seen',String(Date.now()));localStorage.setItem('rti-demo-sound','on');}catch(e){}});
const p=await ctx.newPage();p.on('pageerror',e=>console.log('pageerror',e.message));
await p.goto(SITE,{waitUntil:'load'});await p.evaluate(()=>document.fonts.ready);await p.waitForTimeout(1200);
await p.addStyleTag({content:rd('film.css')});await p.addScriptTag({content:rd('film.js')});await p.waitForTimeout(400);
const cdp=await ctx.newCDPSession(p);let n=0;const meta=[];
cdp.on('Page.screencastFrame',async f=>{const name=String(n++).padStart(5,'0')+'.jpg';fs.writeFileSync(OUT+'/'+name,Buffer.from(f.data,'base64'));meta.push({name,t:f.metadata.timestamp});try{await cdp.send('Page.screencastFrameAck',{sessionId:f.sessionId});}catch(e){}});
await cdp.send('Page.startScreencast',{format:'jpeg',quality:94,maxWidth:1920,maxHeight:1080,everyNthFrame:1});
await p.waitForTimeout(500);
const t0=Date.now();await p.evaluate(()=>document.getElementById('pitch-play').click());
let done=0;
while(Date.now()-t0<SECS*1000){await p.waitForTimeout(400);
  const on=await p.evaluate(()=>!document.getElementById('pitch').hidden).catch(()=>false);
  if(Date.now()-t0>10000&&!on&&!done)done=Date.now();
  if(done&&Date.now()-done>2500)break;}
await cdp.send('Page.stopScreencast');
const plays=await p.evaluate(()=>window.__plays),film=await p.evaluate(()=>window.__film),cuts=film.cuts;
fs.writeFileSync(OUT+'/meta.json',JSON.stringify({t0,frames:meta,plays,cuts,caps:film.caps,labels:film.labels}));
const secs=(Date.now()-t0)/1000;console.log('frames',n,'secs',secs.toFixed(1),'fps',(n/secs).toFixed(1),'plays',plays.length,'cuts',cuts.map(c=>c.why).join(' '));
await b.close();
